//! Zero-dependency crypto for the demo: SHA-256, HMAC-SHA256, base64url, and a
//! constant-time compare. Hand-rolled on purpose — the whole demo, crypto
//! included, pulls in no crates, mirroring Dagr's own zero-dependency ethos.
//!
//! This is small and readable, NOT hardened production crypto. For real systems
//! use a vetted library (ring, RustCrypto). The point here is that the *envelope
//! mechanics* are Dagr's; the algorithm is entirely the caller's choice.

